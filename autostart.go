package main

// install / uninstall 子命令：把当前程序注册为开机自启（Windows）。
//
// 实现方式：HKCU Run 注册表键 + data-dir 下的 VBS 启动器。
//   - 注册表直写（x/sys/windows/registry），不经过 schtasks，无引号转义问题、免管理员；
//   - VBS 以隐藏窗口启动控制台程序，彻底无闪窗（内容用纯 ASCII，避免编码问题）；
//   - 触发时机是"用户登录"而非系统服务：采集桌面（gdigrab）与摄像头（dshow）
//     都要求进程运行在交互式用户会话中，SYSTEM 服务位于 Session 0 采不到。
//
// 主程序启动时会把命令行参数写回配置文件（见 main），因此自启动命令必须
// 显式携带完整参数——install 时从 data-dir 的既有配置重建，避免用户配置
// 被默认值覆盖。

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/linuxsuren/local-onvif-adapter/internal/config"
)

const (
	// autostartRunName HKCU Run 键下的值名（任务管理器"启动"页显示名）。
	autostartRunName = "local-onvif-adapter"
	// autostartVBSName 启动器文件名（位于 data-dir 内）。
	autostartVBSName = "local-onvif-adapter-autostart.vbs"
	autostartRunKey  = `Software\Microsoft\Windows\CurrentVersion\Run`
)

// runInstall 处理 install 子命令，返回进程退出码。
func runInstall(args []string) int {
	fs := flag.NewFlagSet("install", flag.ExitOnError)
	dataDir := fs.String("data-dir", envOr("DATA_DIR", "./data"), "配置持久化目录（自启动沿用该目录）")
	dryRun := fs.Bool("dry-run", false, "只打印将注册的内容，不落盘")
	_ = fs.Parse(args)

	if !autostartSupported() {
		fmt.Fprintln(os.Stderr, "当前平台暂不支持 install 子命令，参考 README「开机自启」手动配置（systemd/launchd）。")
		return 1
	}

	exe, err := os.Executable()
	if err != nil {
		fmt.Fprintf(os.Stderr, "获取可执行文件路径失败: %v\n", err)
		return 1
	}
	exe, err = filepath.Abs(exe)
	if err != nil {
		fmt.Fprintf(os.Stderr, "解析可执行文件路径失败: %v\n", err)
		return 1
	}
	dir, err := filepath.Abs(*dataDir)
	if err != nil {
		fmt.Fprintf(os.Stderr, "解析数据目录路径失败: %v\n", err)
		return 1
	}

	extra, cfgErr := launchArgsFromConfig(dir)
	if cfgErr != nil {
		fmt.Fprintf(os.Stderr, "读取配置失败（%v），将使用默认参数注册\n", cfgErr)
	}

	vbs := vbsContent(exe, dir, extra)
	vbsPath := filepath.Join(dir, autostartVBSName)
	runValue := `wscript.exe //B //Nologo "` + vbsPath + `"`

	fmt.Printf("启动器文件 : %s\n", vbsPath)
	fmt.Printf("注册表键值 : HKCU\\%s\\%s = %s\n", autostartRunKey, autostartRunName, runValue)
	fmt.Printf("启动命令行 : %s -data-dir %s %s\n", exe, dir, strings.Join(extra, " "))
	if *dryRun {
		fmt.Println("（dry-run，未落盘）")
		return 0
	}

	if err := os.MkdirAll(dir, 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "创建数据目录失败: %v\n", err)
		return 1
	}
	// 先写注册表，成功后再落 VBS；VBS 写失败时回滚注册，
	// 避免残留指向不存在文件的注册表项。
	if err := registerAutostart(runValue); err != nil {
		fmt.Fprintf(os.Stderr, "写注册表失败: %v\n", err)
		return 1
	}
	// VBS 只用 ASCII：wscript 按本地编码解析脚本，避免非 ASCII 注释乱码。
	if err := os.WriteFile(vbsPath, []byte(vbs), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "写入启动器失败: %v\n", err)
		_ = unregisterAutostart()
		return 1
	}
	fmt.Println("已注册开机自启（用户登录时静默启动）。")
	fmt.Println("卸载：local-onvif-adapter uninstall")
	fmt.Println("注意：移动可执行文件或数据目录后需重新执行 install。")
	return 0
}

// runUninstall 处理 uninstall 子命令，幂等（未注册时也成功）。
func runUninstall(args []string) int {
	fs := flag.NewFlagSet("uninstall", flag.ExitOnError)
	dataDir := fs.String("data-dir", envOr("DATA_DIR", "./data"), "配置持久化目录（清理其中的启动器文件）")
	_ = fs.Parse(args)

	dir, err := filepath.Abs(*dataDir)
	if err != nil {
		fmt.Fprintf(os.Stderr, "解析数据目录路径失败: %v\n", err)
		return 1
	}
	if err := unregisterAutostart(); err != nil {
		fmt.Fprintf(os.Stderr, "删除注册表键值失败: %v\n", err)
		return 1
	}
	fmt.Println("已移除开机自启注册。")
	vbsPath := filepath.Join(dir, autostartVBSName)
	if err := os.Remove(vbsPath); err == nil {
		fmt.Printf("已清理启动器文件: %s\n", vbsPath)
	}
	return 0
}

// launchArgsFromConfig 从 data-dir 的既有配置重建完整启动参数。
// 主程序每次启动都会用命令行值覆盖配置文件，因此这里必须显式带回
// 当前配置，否则自启动一次就会把用户配置重置为默认值。
func launchArgsFromConfig(dir string) ([]string, error) {
	store, err := config.LoadStore(dir)
	if err != nil {
		return nil, err
	}
	cfg := store.Root().Server
	args := []string{
		"-http-addr", cfg.HTTPAddr,
		"-rtsp-server", strconv.FormatBool(cfg.RTSPEmbedded),
		"-ffmpeg-bin", cfg.FFmpegBin,
	}
	// 注意不携带 -rtsp-port：#15 起 RTSP 端口仅在命令行/环境变量显式指定时
	// 才覆盖配置文件，不携带时配置即权威——用户之后经 UI/API 改的端口在
	// 自启动重启后才能保留；若在此冻结端口值会静默回滚用户的修改。
	if cfg.AdvertiseIP != "" {
		args = append(args, "-advertise-ip", cfg.AdvertiseIP)
	}
	if !cfg.RTSPEmbedded && cfg.RTSPPushAddr != "" {
		args = append(args, "-rtsp-push", cfg.RTSPPushAddr)
	}
	if !cfg.Discovery {
		args = append(args, "-discovery=false")
	}
	return args, nil
}

// vbsContent 生成隐藏窗口启动器的 VBS 内容。
// VBS 语法：字符串内的双引号写成两个双引号；Run 第二参数 0 = 隐藏窗口。
func vbsContent(exe, dataDir string, extraArgs []string) string {
	var sb strings.Builder
	sb.WriteString(`"""`)
	sb.WriteString(exe)
	sb.WriteString(`"" -data-dir ""`)
	sb.WriteString(dataDir)
	sb.WriteString(`""`)
	for _, a := range extraArgs {
		if strings.ContainsAny(a, " \t") {
			sb.WriteString(` ""` + a + `""`)
		} else {
			sb.WriteByte(' ')
			sb.WriteString(a)
		}
	}
	sb.WriteString(`"`)
	return "; Generated by: local-onvif-adapter install\r\n" +
		"; Deleting this file breaks autostart; re-run install to regenerate.\r\n" +
		"; Run with window style 0 (hidden): no console flash on logon.\r\n" +
		"CreateObject(\"WScript.Shell\").Run " + sb.String() + ", 0, False\r\n"
}
