package main

// install / uninstall 子命令：把当前程序注册为开机自启（Windows / Linux / macOS）。
//
// 各平台实现（平台钩子见 autostart_windows.go / autostart_linux.go / autostart_darwin.go）：
//   - Windows：HKCU Run 注册表键 + data-dir 下的 VBS 启动器（用户登录时静默启动）；
//   - Linux：systemd 用户单元（~/.config/systemd/user/）+ enable --now，并尝试
//     loginctl enable-linger 让服务在开机后无需登录即启动；
//   - macOS：launchd LaunchAgent（~/Library/LaunchAgents/）+ launchctl load。
//
// 主程序启动时会把命令行参数写回配置文件（见 main），因此自启动命令必须
// 显式携带完整参数——install 时从 data-dir 的既有配置重建，避免用户配置
// 被默认值覆盖。

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/linuxsuren/local-onvif-adapter/internal/config"
)

const (
	// autostartRunName HKCU Run 键下的值名（任务管理器"启动"页显示名）。
	autostartRunName = "local-onvif-adapter"
	// autostartVBSName 启动器文件名（位于 data-dir 内）。
	autostartVBSName = "local-onvif-adapter-autostart.vbs"
	autostartRunKey  = `Software\Microsoft\Windows\CurrentVersion\Run`

	// autostartUnitName systemd 用户单元文件名（Linux）。
	autostartUnitName = "local-onvif-adapter.service"
	// autostartPlistName / autostartLabel launchd 作业文件名与标签（macOS）。
	autostartPlistName = "com.linuxsuren.local-onvif-adapter.plist"
	autostartLabel     = "com.linuxsuren.local-onvif-adapter"
)

// runInstall 处理 install 子命令，返回进程退出码。
func runInstall(args []string) int {
	fs := flag.NewFlagSet("install", flag.ExitOnError)
	dataDir := fs.String("data-dir", envOr("DATA_DIR", "./data"), "配置持久化目录（自启动沿用该目录）")
	dryRun := fs.Bool("dry-run", false, "只打印将注册的内容，不落盘")
	_ = fs.Parse(args)

	if !autostartSupported() {
		fmt.Fprintln(os.Stderr, "当前平台暂不支持 install 子命令，参考 README「开机自启」手动配置。")
		return 1
	}

	exe, err := os.Executable()
	if err != nil {
		fmt.Fprintf(os.Stderr, "获取可执行文件路径失败: %v\n", err)
		return 1
	}
	exe, err = filepath.Abs(exe)
	if err != nil {
		fmt.Fprintf(os.Stderr, "解析可执行文件路径失败: %v\n", err)
		return 1
	}
	dir, err := filepath.Abs(*dataDir)
	if err != nil {
		fmt.Fprintf(os.Stderr, "解析数据目录路径失败: %v\n", err)
		return 1
	}

	extra, cfgErr := launchArgsFromConfig(dir)
	if cfgErr != nil {
		fmt.Fprintf(os.Stderr, "读取配置失败（%v），将使用默认参数注册\n", cfgErr)
	}

	fmt.Printf("可执行文件: %s\n", exe)
	fmt.Printf("数据目录  : %s\n", dir)
	fmt.Printf("启动参数  : -data-dir %s %s\n", dir, strings.Join(extra, " "))
	if err := installAutostart(exe, dir, extra, *dryRun); err != nil {
		fmt.Fprintf(os.Stderr, "注册开机自启失败: %v\n", err)
		return 1
	}
	return 0
}

// runUninstall 处理 uninstall 子命令，幂等（未注册时也成功）。
func runUninstall(args []string) int {
	fs := flag.NewFlagSet("uninstall", flag.ExitOnError)
	dataDir := fs.String("data-dir", envOr("DATA_DIR", "./data"), "配置持久化目录（清理其中的启动器文件）")
	_ = fs.Parse(args)

	dir, err := filepath.Abs(*dataDir)
	if err != nil {
		fmt.Fprintf(os.Stderr, "解析数据目录路径失败: %v\n", err)
		return 1
	}
	if err := uninstallAutostart(dir); err != nil {
		fmt.Fprintf(os.Stderr, "移除开机自启失败: %v\n", err)
		return 1
	}
	return 0
}

// launchArgsFromConfig 从 data-dir 的既有配置重建完整启动参数。
// 主程序每次启动都会用命令行值覆盖配置文件，因此这里必须显式带回
// 当前配置，否则自启动一次就会把用户配置重置为默认值。
func launchArgsFromConfig(dir string) ([]string, error) {
	store, err := config.LoadStore(dir)
	if err != nil {
		return nil, err
	}
	cfg := store.Root().Server
	args := []string{
		"-http-addr", cfg.HTTPAddr,
		"-rtsp-server", strconv.FormatBool(cfg.RTSPEmbedded),
		"-ffmpeg-bin", cfg.FFmpegBin,
	}
	// 注意不携带 -rtsp-port：#15 起 RTSP 端口仅在命令行/环境变量显式指定时
	// 才覆盖配置文件，不携带时配置即权威——用户之后经 UI/API 改的端口在
	// 自启动重启后才能保留；若在此冻结端口值会静默回滚用户的修改。
	if cfg.AdvertiseIP != "" {
		args = append(args, "-advertise-ip", cfg.AdvertiseIP)
	}
	if !cfg.RTSPEmbedded && cfg.RTSPPushAddr != "" {
		args = append(args, "-rtsp-push", cfg.RTSPPushAddr)
	}
	if !cfg.Discovery {
		args = append(args, "-discovery=false")
	}
	return args, nil
}

// vbsContent 生成隐藏窗口启动器的 VBS 内容（Windows）。
// VBS 语法：字符串内的双引号写成两个双引号；Run 第二参数 0 = 隐藏窗口。
func vbsContent(exe, dataDir string, extraArgs []string) string {
	var sb strings.Builder
	sb.WriteString(`"""`)
	sb.WriteString(exe)
	sb.WriteString(`"" -data-dir ""`)
	sb.WriteString(dataDir)
	sb.WriteString(`""`)
	for _, a := range extraArgs {
		if strings.ContainsAny(a, " \t") {
			sb.WriteString(` ""` + a + `""`)
		} else {
			sb.WriteByte(' ')
			sb.WriteString(a)
		}
	}
	sb.WriteString(`"`)
	return "; Generated by: local-onvif-adapter install\r\n" +
		"; Deleting this file breaks autostart; re-run install to regenerate.\r\n" +
		"; Run with window style 0 (hidden): no console flash on logon.\r\n" +
		"CreateObject(\"WScript.Shell\").Run " + sb.String() + ", 0, False\r\n"
}

// systemdUnitContent 生成 systemd 用户单元内容（Linux）。
// ExecStart 参数含空格/引号时按 systemd 规则加引号转义。
func systemdUnitContent(exe, dataDir string, extraArgs []string) string {
	var sb strings.Builder
	sb.WriteString("# Generated by: local-onvif-adapter install\n")
	sb.WriteString("# Deleting this file breaks autostart; re-run install to regenerate.\n")
	sb.WriteString("[Unit]\n")
	sb.WriteString("Description=local ONVIF adapter\n")
	sb.WriteString("After=network-online.target\n")
	sb.WriteString("Wants=network-online.target\n")
	sb.WriteString("\n[Service]\n")
	sb.WriteString("ExecStart=" + quoteSystemdArg(exe))
	sb.WriteString(" -data-dir " + quoteSystemdArg(dataDir))
	for _, a := range extraArgs {
		sb.WriteByte(' ')
		sb.WriteString(quoteSystemdArg(a))
	}
	sb.WriteString("\n")
	sb.WriteString("Restart=on-failure\n")
	sb.WriteString("RestartSec=3\n")
	sb.WriteString("\n[Install]\n")
	sb.WriteString("WantedBy=default.target\n")
	return sb.String()
}

// quoteSystemdArg systemd ExecStart 参数转义：含空白或引号时用双引号包裹，
// 内部引号反斜杠转义；空参数写成一对引号（否则会被 systemd 丢弃）。
func quoteSystemdArg(a string) string {
	if a == "" {
		return `""`
	}
	if strings.ContainsAny(a, " \t\"") {
		return `"` + strings.ReplaceAll(a, `"`, `\"`) + `"`
	}
	return a
}

// launchdPlistContent 生成 launchd LaunchAgent plist 内容（macOS）。
// KeepAlive 采用 SuccessfulExit=false：异常退出时重启、正常退出不拉起，
// 与 systemd 的 Restart=on-failure 语义对齐。日志落到 data-dir 方便排查。
func launchdPlistContent(exe, dataDir string, extraArgs []string) string {
	var sb strings.Builder
	sb.WriteString("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n")
	sb.WriteString("<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n")
	sb.WriteString("<plist version=\"1.0\"><dict>\n")
	sb.WriteString("  <key>Label</key>\n")
	sb.WriteString("  <string>" + xmlEscape(autostartLabel) + "</string>\n")
	sb.WriteString("  <key>ProgramArguments</key>\n")
	sb.WriteString("  <array>\n")
	for _, a := range append([]string{exe, "-data-dir", dataDir}, extraArgs...) {
		sb.WriteString("    <string>" + xmlEscape(a) + "</string>\n")
	}
	sb.WriteString("  </array>\n")
	sb.WriteString("  <key>RunAtLoad</key>\n")
	sb.WriteString("  <true/>\n")
	sb.WriteString("  <key>KeepAlive</key>\n")
	sb.WriteString("  <dict>\n    <key>SuccessfulExit</key>\n    <false/>\n  </dict>\n")
	sb.WriteString("  <key>StandardOutPath</key>\n")
	sb.WriteString("  <string>" + xmlEscape(filepath.Join(dataDir, "autostart.out.log")) + "</string>\n")
	sb.WriteString("  <key>StandardErrorPath</key>\n")
	sb.WriteString("  <string>" + xmlEscape(filepath.Join(dataDir, "autostart.err.log")) + "</string>\n")
	sb.WriteString("</dict></plist>\n")
	return sb.String()
}

var xmlEscaper = strings.NewReplacer(
	"&", "&amp;",
	"<", "&lt;",
	">", "&gt;",
	`"`, "&quot;",
	"'", "&apos;",
)

// xmlEscape 转义 XML 文本中的保留字符（路径含 & 或 < 时 plist 才能正确解析）。
func xmlEscape(s string) string {
	return xmlEscaper.Replace(s)
}
